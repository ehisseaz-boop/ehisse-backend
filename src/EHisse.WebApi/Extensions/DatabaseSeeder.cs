using EHisse.Domain.Entities;
using EHisse.Domain.Enums;
using EHisse.Persistence.Context;
using Microsoft.EntityFrameworkCore;

namespace EHisse.WebApi.Extensions;

public static class DatabaseSeeder
{
    public static void SeedDatabase(IApplicationBuilder app)
    {
        using var scope = app.ApplicationServices.CreateScope();
        var context = scope.ServiceProvider.GetRequiredService<AppDbContext>();

        try
        {
            context.Database.Migrate();
        }
        catch
        {
            context.Database.EnsureCreated();
        }

        // Add Pin and IdCardImageUrl columns to Users table if they do not exist
        try
        {
            context.Database.ExecuteSqlRaw(@"
                DO $$ 
                BEGIN 
                    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='Users' AND column_name='Pin') THEN
                        ALTER TABLE ""Users"" ADD COLUMN ""Pin"" text NULL;
                    END IF;
                    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='Users' AND column_name='IdCardImageUrl') THEN
                        ALTER TABLE ""Users"" ADD COLUMN ""IdCardImageUrl"" text NULL;
                    END IF;
                    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='SellerProfiles' AND column_name='ShopPhotoUrl') THEN
                        ALTER TABLE ""SellerProfiles"" ADD COLUMN ""ShopPhotoUrl"" text NULL;
                    END IF;
                    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='SellerProfiles' AND column_name='Latitude') THEN
                        ALTER TABLE ""SellerProfiles"" ADD COLUMN ""Latitude"" double precision NULL;
                    END IF;
                    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='SellerProfiles' AND column_name='Longitude') THEN
                        ALTER TABLE ""SellerProfiles"" ADD COLUMN ""Longitude"" double precision NULL;
                    END IF;
                END $$;

                                CREATE TABLE IF NOT EXISTS ""SiteSettings"" (
                    ""Id"" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    ""Key"" text NOT NULL UNIQUE,
                    ""Value"" text NULL,
                    ""Description"" text NULL,
                    ""LastModifiedDate"" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
                );
                CREATE TABLE IF NOT EXISTS ""SellerReviews"" (
                    ""Id"" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    ""SellerId"" integer NOT NULL REFERENCES ""SellerProfiles""(""Id"") ON DELETE CASCADE,
                    ""UserId"" integer NOT NULL REFERENCES ""Users""(""Id"") ON DELETE CASCADE,
                    ""SparePartId"" integer NULL REFERENCES ""SpareParts""(""Id"") ON DELETE SET NULL,
                    ""Rating"" integer NOT NULL,
                    ""Comment"" text NOT NULL,
                    ""CreatedDate"" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
                );
            ");
        }
        catch { }

                // Default Site Settings Seeder
        try
        {
            var defaultSettings = new Dictionary<string, (string Value, string Description)>
            {
                { "AboutText", ("Mobil telefon, planşet və noutbuk ehtiyat hissələrinin ən böyük axtarış və sifariş platforması. Ustalar və anbarlar üçün etibarlı həll.", "Saytın haqqında qısa mətni") },
                { "AboutFull", ("e-hisse.az Azərbaycan üzrə mobil telefon, planşet və noutbuk təmiri ustaları ilə etibarlı ehtiyat hissəsi satıcılarını bir araya gətirən müasir platformadır. Məqsədimiz bazarda axtarılan hər növ orijinal və A-Class ehtiyat hissəsini sürətli, şəffaf və ən münasib qiymətlərlə əlçatan etməkdir.", "Geniş Haqqımızda mətni") },
                { "ContactPhone", ("+994 10 252 32 26", "Əlaqə telefonu") },
                { "ContactWhatsApp", ("+994 10 396 15 01", "WhatsApp nömrəsi") },
                { "ContactEmail", ("info@e-hisse.az", "Rəsmi əlaqə e-poçt ünvanı") },
                { "ContactAddress", ("Bakı şəh., 28 May / Nizami küç.", "Ofis / Anbar ünvanı") },
                { "AnnouncementBanner", ("", "Saytın yuxarısında bildiriş/elan banneri (boşdursa gizlənir)") }
            };

            foreach (var kvp in defaultSettings)
            {
                if (!context.SiteSettings.Any(s => s.Key == kvp.Key))
                {
                    context.SiteSettings.Add(new SiteSetting
                    {
                        Key = kvp.Key,
                        Value = kvp.Value.Value,
                        Description = kvp.Value.Description,
                        LastModifiedDate = DateTime.UtcNow
                    });
                }
            }
            context.SaveChanges();
        }
        catch { }

                // Fix PostgreSQL sequences for all primary keys
        try
        {
            context.Database.ExecuteSqlRaw(@"
                DO 
                DECLARE
                    tbl record;
                    max_id integer;
                    seq_name text;
                BEGIN
                    FOR tbl IN 
                        SELECT table_name 
                        FROM information_schema.tables 
                        WHERE table_schema = 'public' 
                          AND table_type = 'BASE TABLE'
                    LOOP
                        BEGIN
                            seq_name := pg_get_serial_sequence('""' || tbl.table_name || '""', 'Id');
                            IF seq_name IS NOT NULL THEN
                                EXECUTE format('SELECT COALESCE(MAX(""Id""), 0) FROM ""%I""', tbl.table_name) INTO max_id;
                                IF max_id > 0 THEN
                                    EXECUTE format('SELECT setval(%L, %s)', seq_name, max_id);
                                END IF;
                            END IF;
                        EXCEPTION WHEN OTHERS THEN
                            -- skip tables without integer Id
                        END;
                    END LOOP;
                END ;
            ");
        }
        catch { }

        // Ensure Admin user credentials match updated configuration
        try
        {
            var adminUser = context.Users.FirstOrDefault(u => u.Role == UserRole.Admin || u.Username == "admin" || u.Username == "admin_user");
            if (adminUser != null)
            {
                adminUser.Username = "admin_user";
                adminUser.PasswordHash = BCrypt.Net.BCrypt.HashPassword("admin_panel2026#");
                adminUser.ApprovalStatus = ApprovalStatus.Approved;
                adminUser.IsBlocked = false;
                context.SaveChanges();
            }
            else
            {
                context.Users.Add(new User
                {
                    Username = "admin_user",
                    Email = "admin@example.com",
                    PasswordHash = BCrypt.Net.BCrypt.HashPassword("admin_panel2026#"),
                    Role = UserRole.Admin,
                    FirstName = "Baş",
                    LastName = "Administrator",
                    Phone = "+994000000000",
                    ApprovalStatus = ApprovalStatus.Approved,
                    IsBlocked = false
                });
                context.SaveChanges();
            }
        }
        catch { }

        // Fix any null SKUs in legacy data
        var nullSkus = context.SpareParts.Where(s => s.SKU == null || s.SKU == "").ToList();
        if (nullSkus.Any())
        {
            foreach (var item in nullSkus)
            {
                item.SKU = "LEGACY-" + item.Id;
            }
            context.SaveChanges();
        }

        var categories = context.Categories.ToList();
        foreach (var c in categories)
        {
            if (c.Name.Contains("Avadanl") && (c.Name.Contains("b?k?") || c.Name.Contains("bəkə")))
            {
                c.Name = "Şəbəkə Avadanlıqları";
            }
            else if (c.Name.Contains("T?mir") || c.Name.Contains("Al?tl?r") || c.Name.Contains("Alətlər"))
            {
                c.Name = "Alətlər və Təmir Avadanlıqları";
            }
            else if (c.Name.Contains("Saat"))
            {
                c.Name = "Smart Saat ehtiyat hissələri";
            }
            else if (c.Name.Contains("Qulaq"))
            {
                c.Name = "Qulaqlıq ehtiyat hissələri";
            }
        }
        context.SaveChanges();

        // Fix part type names: ensure 'Ekranlar' and 'Batareyalar'
        var partTypesToFix = context.SparePartTypes.ToList();
        foreach (var pt in partTypesToFix)
        {
            if (pt.Name.Contains("ekran", StringComparison.OrdinalIgnoreCase) && !pt.Name.Contains("şüşə", StringComparison.OrdinalIgnoreCase) && !pt.Name.Contains("suse", StringComparison.OrdinalIgnoreCase))
            {
                pt.Name = "Ekranlar";
            }
            else if (pt.Name.Contains("batarey", StringComparison.OrdinalIgnoreCase))
            {
                pt.Name = "Batareyalar";
            }
            else if (pt.Name.Contains("Telefon üçün sensorlar və ekran şüşələri", StringComparison.OrdinalIgnoreCase))
            {
                pt.Name = "Sensor və ekran şüşələri";
            }
        }
        context.SaveChanges();

        // Also clean up any legacy ad titles containing "telefon üçün"
        try
        {
            context.Database.ExecuteSqlRaw(@"
                UPDATE ""SpareParts""
                SET ""Title"" = REPLACE(REPLACE(REPLACE(""Title"", 'Telefon üçün ekranlar', 'Ekranlar'), 'Telefon üçün batareyalar', 'Batareyalar'), 'Telefon üçün ', '')
                WHERE ""Title"" ILIKE '%telefon üçün%';

                UPDATE ""SparePartTypes""
                SET ""Name"" = 'Ekranlar'
                WHERE ""Key"" = 'SCREEN' OR ""Name"" ILIKE '%telefon üçün ekran%';

                UPDATE ""SparePartTypes""
                SET ""Name"" = 'Batareyalar'
                WHERE ""Key"" = 'BATTERY' OR ""Name"" ILIKE '%telefon üçün batarey%';
            ");
        }
        catch { }

        // Seeding default categories if needed
        if (context.Categories.Count() < 10)
        {
            var newCategories = new[]
            {
                new Category { Name = "Smart Saat ehtiyat hissələri", DisplayOrder = 4, IsActive = true },
                new Category { Name = "Qulaqlıq ehtiyat hissələri", DisplayOrder = 5, IsActive = true },
                new Category { Name = "Kompüter (PC) ehtiyat hissələri", DisplayOrder = 6, IsActive = true },
                new Category { Name = "Televizor ehtiyat hissələri", DisplayOrder = 7, IsActive = true },
                new Category { Name = "Oyun Konsolu ehtiyat hissələri", DisplayOrder = 8, IsActive = true },
                new Category { Name = "Foto/Video Kamera ehtiyat hissələri", DisplayOrder = 9, IsActive = true },
                new Category { Name = "Alətlər və Təmir Avadanlıqları", DisplayOrder = 10, IsActive = true },
                new Category { Name = "Dron ehtiyat hissələri", DisplayOrder = 11, IsActive = true },
                new Category { Name = "Elektrikli Samokat ehtiyat hissələri", DisplayOrder = 12, IsActive = true },
                new Category { Name = "Şəbəkə Avadanlıqları", DisplayOrder = 13, IsActive = true },
                new Category { Name = "Adapterlər və Kabellər", DisplayOrder = 14, IsActive = true }
            };

            foreach (var cat in newCategories)
            {
                if (!context.Categories.Any(c => c.Name == cat.Name))
                {
                    context.Categories.Add(cat);
                }
            }
            context.SaveChanges();
        }

        // Seeding default relationships for empty categories
        var emptyCategories = context.Categories.Where(c => !context.DeviceModels.Any(m => m.CategoryId == c.Id)).ToList();
        if (emptyCategories.Any())
        {
            var otherBrand = context.DeviceBrands.FirstOrDefault(b => b.Name == "Digər");
            if (otherBrand == null)
            {
                otherBrand = new DeviceBrand { Name = "Digər", IsActive = true };
                context.DeviceBrands.Add(otherBrand);
                context.SaveChanges();
            }

            var otherPartType = context.SparePartTypes.FirstOrDefault(pt => pt.Name == "Digər");
            if (otherPartType == null)
            {
                otherPartType = new SparePartType { Name = "Digər", Key = "other", IsAccessory = false, IsPortable = false };
                context.SparePartTypes.Add(otherPartType);
                context.SaveChanges();
            }

            foreach (var cat in emptyCategories)
            {
                if (!context.CategoryBrands.Any(cb => cb.CategoryId == cat.Id && cb.BrandId == otherBrand.Id))
                    context.CategoryBrands.Add(new CategoryBrand { CategoryId = cat.Id, BrandId = otherBrand.Id });

                if (!context.CategoryPartTypes.Any(cpt => cpt.CategoryId == cat.Id && cpt.PartTypeId == otherPartType.Id))
                    context.CategoryPartTypes.Add(new CategoryPartType { CategoryId = cat.Id, PartTypeId = otherPartType.Id });

                context.DeviceModels.Add(new DeviceModel
                {
                    CategoryId = cat.Id,
                    BrandId = otherBrand.Id,
                    Name = "Digər (Ümumi)",
                    ModelCode = "OTHER",
                    ReleaseYear = DateTime.Now.Year,
                    IsActive = true
                });
            }
            context.SaveChanges();
        }

        // Seed sample products if needed
        if (context.SpareParts.Count() < 17)
        {
            var firstSeller = context.SellerProfiles.FirstOrDefault();
            var firstModel = context.DeviceModels.FirstOrDefault();
            var firstPartType = context.SparePartTypes.FirstOrDefault();
            var firstQuality = context.QualityTypes.FirstOrDefault();

            if (firstSeller != null && firstModel != null && firstPartType != null && firstQuality != null)
            {
                var rnd = new Random();
                for (int i = 1; i <= 15; i++)
                {
                    context.SpareParts.Add(new SparePart
                    {
                        Title = $"Nümunəvi Ehtiyat Hissəsi {i}",
                        Description = $"Bu sistem tərəfindən avtomatik əlavə edilmiş test məhsuludur {i}.",
                        Price = rnd.Next(10, 500) + 0.99m,
                        StockQuantity = rnd.Next(1, 100),
                        DeviceModelId = firstModel.Id,
                        PartTypeId = firstPartType.Id,
                        QualityTypeId = firstQuality.Id,
                        SellerId = firstSeller.Id,
                        ModerationStatus = ApprovalStatus.Approved,
                        IsDeleted = false,
                        CreatedDate = DateTime.UtcNow,
                        ViewCount = 0,
                        SKU = $"DUMMY-SKU-{i}"
                    });
                }
                context.SaveChanges();
            }
        }

        // Seed images for spare parts if missing
        var sparePartsWithoutImages = context.SpareParts.Include(sp => sp.Images).Where(sp => !sp.Images.Any()).ToList();
        if (sparePartsWithoutImages.Any())
        {
            var random = new Random();
            var availableImages = new[]
            {
                "/images/images (1).jpg", "/images/images (2).jpg", "/images/images (3).jpg",
                "/images/images (4).jpg", "/images/images (5).jpg", "/images/images (6).jpg",
                "/images/images (7).jpg", "/images/images.jpg"
            };

            foreach (var sp in sparePartsWithoutImages)
            {
                sp.Images.Add(new SparePartImage
                {
                    ImageUrl = availableImages[random.Next(availableImages.Length)],
                    IsMain = true,
                    DisplayOrder = 1
                });
            }
            context.SaveChanges();
        }
    }
}
